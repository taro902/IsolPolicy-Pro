    private PixelFont() {
    }

    private static void put(char c, int r0, int r1, int r2, int r3, int r4, int r5, int r6) {
        TABLE[c] = new int[]{r0, r1, r2, r3, r4, r5, r6};
    }

    public static int measureWidth(String text, int scale) {
        if (text == null || text.isEmpty()) {
            return 0;
        }
        return (text.length() * ADVANCE - 1) * scale;
    }

    public static int lineHeight(int scale) {
        return GLYPH_H * scale;
    }

    public static void draw(Canvas canvas, String text, float left, float top, int scale, Paint paint) {
        if (text == null || text.isEmpty() || scale <= 0) {
            return;
        }
        int len = text.length();
        float curX = Math.round(left);
        float baseY = Math.round(top);
        int stepX = ADVANCE * scale;
        for (int i = 0; i < len; i++) {
            char ch = text.charAt(i);
            if (ch >= 'a' && ch <= 'z') {
                ch = (char) (ch - 32);
            }
            int[] rows = ch < 128 ? TABLE[ch] : null;
            if (rows != null) {
                for (int r = 0; r < GLYPH_H; r++) {
                    int bits = rows[r];
                    if (bits == 0) {
                        continue;
                    }
                    float py = baseY + (r * scale);
                    for (int c = 0; c < GLYPH_W; c++) {
                        if ((bits & (1 << (4 - c))) != 0) {
                            float px = curX + (c * scale);
                            canvas.drawRect(px, py, px + scale, py + scale, paint);
                        }
                    }
                }
            }
            curX += stepX;
        }
    }

    public static void drawCentered(Canvas canvas, String text, float centerX, float centerY, int scale, Paint paint) {
        int w = measureWidth(text, scale);
        int h = lineHeight(scale);
        draw(canvas, text, centerX - (w * 0.5f), centerY - (h * 0.5f), scale, paint);
    }

    public static void drawRight(Canvas canvas, String text, float rightX, float top, int scale, Paint paint) {
        int w = measureWidth(text, scale);
        draw(canvas, text, rightX - w, top, scale, paint);
    }
